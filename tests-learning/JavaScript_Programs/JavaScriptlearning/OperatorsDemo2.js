let i=5, j=5;
console.log(i);
console.log(j);

//++i --> pre-increment
console.log(++i);
let result = ++j;
console.log(result);

let x=5, y=5;
//i++ --> post-increment
console.log(x++);
console.log(x);

//--x; --> pre-decrement
let m=5, n=5;
console.log(--m);

//x--; --> post-decrement
let a=5, b=5;
console.log(a--);
console.log(a);